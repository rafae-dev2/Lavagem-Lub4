from pathlib import Path
from playwright.sync_api import sync_playwright,expect
import json
OUT=Path('/home/ubuntu/entrega-tv-externas-premium');OUT.mkdir(exist_ok=True)
with sync_playwright() as p:
 b=p.chromium.launch(executable_path='/usr/bin/chromium',headless=True,args=['--no-sandbox'])
 page=b.new_page(viewport={'width':1920,'height':1080})
 errors=[];page.on('pageerror',lambda e:errors.append(str(e)))
 page.route('**/*',lambda r:r.continue_() if r.request.url.startswith('http://127.0.0.1:3000/') else r.abort())
 page.goto('http://127.0.0.1:3000/tv-test.html');page.wait_for_selector('.tv-order')
 page.evaluate('window.tvTestMany()');expect(page.get_by_role('button',name='Painel Emergenciais',exact=True)).to_contain_text('20')
 page.get_by_role('button',name='Painel Ordens Externas',exact=True).click()
 expect(page.locator('.tv-monitor')).to_have_attribute('data-panel','external')
 assert 1<=int(page.locator('.tv-monitor').get_attribute('data-page-size'))<=12
 expect(page.locator('.tv-summary > div').first.locator('strong')).to_have_text('15')
 assert page.locator('.tv-order').count()==int(page.locator('.tv-monitor').get_attribute('data-page-size'))
 assert all('Oficina Premium Externa' in t for t in page.locator('.tv-order').all_inner_texts())
 page.get_by_role('button',name='Configurar filtros do monitor').click()
 expect(page.get_by_label('Classe',exact=True)).to_be_disabled()
 expect(page.get_by_label('Origem / oficina',exact=True)).to_be_disabled()
 page.get_by_label('Buscar frota, OS, equipamento ou narrativa',exact=True).fill('5020')
 expect(page.locator('.tv-summary > div').first.locator('strong')).to_have_text('01')
 page.get_by_role('button',name='Fechar painel',exact=True).click()
 page.get_by_role('button',name='Painel Emergenciais',exact=True).click()
 expect(page.locator('.tv-summary > div').first.locator('strong')).to_have_text('20')
 page.get_by_role('button',name='Painel Ordens Externas',exact=True).click()
 expect(page.locator('.tv-summary > div').first.locator('strong')).to_have_text('01')
 page.get_by_role('button',name='Configurar filtros do monitor').click()
 page.get_by_label('Buscar frota, OS, equipamento ou narrativa',exact=True).fill('')
 page.get_by_label('Tempo por painel',exact=True).select_option('5')
 page.get_by_role('button',name='Fechar painel',exact=True).click()
 page.get_by_role('button',name='Painel Emergenciais',exact=True).click()
 page.get_by_role('button',name='Apresentar na TV',exact=True).click()
 page.wait_for_timeout(350)
 assert page.locator('.tv-monitor').evaluate('(e)=>e.scrollHeight<=e.clientHeight+2'),'12 cards não cabem em1080p'
 assert page.locator('.tv-order').first.evaluate("e=>e.querySelector('footer').getBoundingClientRect().bottom<e.getBoundingClientRect().bottom-3"),'rodapé do card cortado'
 page.screenshot(path=str(OUT/'previa-emergenciais-escuro.png'))
 expect(page.locator('.tv-monitor[data-panel="external"]')).to_be_visible(timeout=7000)
 expect(page.locator('.tv-monitor[data-panel="emergency"]')).to_be_visible(timeout=7000)
 expect(page.locator('.tv-page-controls')).to_contain_text('Página 2 de')
 page.get_by_role('button',name='Pausar rodízio').click()
 panel=page.locator('.tv-monitor').get_attribute('data-panel');page.wait_for_timeout(5300)
 assert page.locator('.tv-monitor').get_attribute('data-panel')==panel
 page.get_by_role('button',name='Painel Ordens Externas',exact=True).click()
 page.get_by_role('button',name='Página anterior',exact=True).click()
 page.get_by_role('button',name='Ativar modo claro premium',exact=True).click()
 expect(page.locator('.tv-monitor')).to_have_attribute('data-tv-theme','light')
 page.wait_for_timeout(350)
 assert page.locator('.tv-monitor').evaluate('(e)=>e.scrollHeight<=e.clientHeight+2')
 page.screenshot(path=str(OUT/'previa-externas-claro.png'))
 page.locator('.tv-order').first.get_by_role('button').click();expect(page.get_by_role('dialog')).to_be_visible()
 expect(page.locator('.tv-dialog')).to_have_attribute('data-tv-theme','light')
 page.keyboard.press('Escape');page.get_by_role('button',name='Sair da apresentação TV',exact=True).click()
 page.reload();page.wait_for_selector('.tv-order');expect(page.locator('.tv-monitor')).to_have_attribute('data-tv-theme','light')
 page.get_by_role('button',name='Configurar filtros do monitor').click()
 expect(page.get_by_label('Tempo por painel',exact=True)).to_have_value('5')
 page.set_viewport_size({'width':390,'height':844});page.wait_for_timeout(250)
 assert page.evaluate('document.documentElement.scrollWidth<=window.innerWidth'),'overflow horizontal celular'
 page.screenshot(path=str(OUT/'previa-filtros-claro-celular.png'))
 assert not errors,errors
 b.close()
(OUT/'validacao-tv-paineis.json').write_text(json.dumps({'status':'aprovado','dados':'fictícios e tráfego externo bloqueado','checks':['somente externas das frotas Apoio','filtros independentes','classe/oficina externas fixas','cards adaptados ao espaço em1080p','alternância5s e avanço de páginas independentes','pausa manual','tema claro em monitor e modal','persistência','celular sem overflow']},ensure_ascii=False,indent=2)+'\n')
print('OK: painéis externos/emergenciais, alternância, páginas, densidade adaptativa, tema claro, filtros, persistência e celular.')

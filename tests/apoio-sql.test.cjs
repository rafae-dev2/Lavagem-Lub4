// Requer npm install --no-save @electric-sql/pglite.
// Todo o banco deste teste é isolado em memória. Não usa o Supabase remoto.
const { PGlite } = require('@electric-sql/pglite');
const fs = require('node:fs');
const assert = require('node:assert/strict');
(async () => {
  const db = new PGlite();
  try {
    await db.exec('create role anon; create role authenticated; create role service_role bypassrls;');
    await db.exec(fs.readFileSync('supabase/APOIO_SETUP.sql', 'utf8'));
    await db.exec('set role anon;');
    await db.query("insert into public.apoio_grupos (id,nome,cor) values ('teste','Grupo de teste','#00aa00')");
    await db.query("insert into public.apoio_frotas (frota,grupo_id,nome) values ('001','teste','')");
    assert.equal((await db.query('select * from public.apoio_frotas')).rows[0].nome, '');
    await assert.rejects(db.query('select public.claim_apoio_sync()'), /permission denied/i);
    await assert.rejects(db.query("insert into public.apoio_sync(id) values(1)"), /permission denied/i);
    await assert.rejects(db.query("delete from public.apoio_ordens"), /permission denied/i);
    await assert.rejects(db.query("delete from public.apoio_grupos where id='teste'"), /foreign key/i);
    await db.exec('reset role;');
    const snapshot = (minutes, ids) => ({ ok: true, atualizado: new Date(Date.now() - minutes * 60000).toISOString(), total: ids.length, ordens: ids.map(id => ({ os: String(id), eq: '001', modelo: 'Fixture de teste', grupo: '', setor: '', ponto: '', origem: 'Oficina', prestador: '', status: 'Programada', entrada: '', prev: '', narrativa: '' })) });
    const apply = p => db.query('select public.aplicar_apoio_snapshot($1::jsonb) as result', [JSON.stringify(p)]);
    const list = async () => (await db.query('select * from public.apoio_ordens order by os')).rows;
    const first = snapshot(5, [1,2]);
    await apply(first);
    let orders = await list();
    assert.equal(orders.length, 2); assert.ok(orders.every(o => o.ativo));
    const firstSeen = String(orders[0].primeira_vista);
    await assert.rejects(apply({ ...snapshot(4, [1]), total: 2 }), /total difere/i);
    assert.equal((await list()).filter(o => o.ativo).length, 2);
    await apply(snapshot(6, [1]));
    assert.equal((await list()).filter(o => o.ativo).length, 2, 'snapshot antigo não remove ordens');
    await apply({ ...first, total: 0, ordens: [] });
    assert.equal((await list()).filter(o => o.ativo).length, 2, 'snapshot igual não remove ordens');
    await apply(snapshot(4, [1]));
    orders = await list();
    assert.equal(orders[0].ativo, true); assert.equal(orders[1].ativo, false);
    assert.ok(orders[1].ausente_desde); assert.equal(orders[1].status, 'Programada');
    await apply(snapshot(3, [1,2]));
    orders = await list();
    assert.equal(orders.length, 2); assert.ok(orders.every(o => o.ativo && o.ausente_desde === null));
    assert.equal(String(orders[0].primeira_vista), firstSeen);
    const validSync = (await db.query('select * from public.apoio_sync')).rows[0];
    await db.query("select public.registrar_apoio_sync_erro('falha de teste')");
    const failedSync = (await db.query('select * from public.apoio_sync')).rows[0];
    assert.equal(String(validSync.fonte_atualizada), String(failedSync.fonte_atualizada));
    assert.equal(failedSync.erro, 'falha de teste');
    assert.ok((await list()).every(o => o.ativo));
    await assert.rejects(apply(snapshot(76, [])), /75 minutos/i);
    await assert.rejects(apply(snapshot(-6, [])), /futuro/i);
    assert.ok((await list()).every(o => o.ativo));
    const claim1 = await db.query('select public.claim_apoio_sync() as ok');
    const claim2 = await db.query('select public.claim_apoio_sync() as ok');
    assert.equal(claim1.rows[0].ok, true); assert.equal(claim2.rows[0].ok, false);
    await db.query("update public.apoio_sync set consulta_iniciada_em=now()-interval '1 minute'");
    assert.equal((await db.query('select public.claim_apoio_sync() as ok')).rows[0].ok, true);
    const oldToken = (await db.query('select consulta_iniciada_em from public.apoio_sync')).rows[0].consulta_iniciada_em;
    await db.query("update public.apoio_sync set consulta_iniciada_em=now()-interval '1 minute', consulta_em_andamento=false");
    const token = (await db.query('select public.iniciar_apoio_sync() as token')).rows[0].token;
    assert.ok(token);
    assert.equal((await db.query('select public.iniciar_apoio_sync() as token')).rows[0].token, null, 'consulta em andamento bloqueia sobreposição');
    await db.query('select public.concluir_apoio_sync($1::jsonb,$2::timestamptz)', [JSON.stringify(snapshot(2,[1,2])), token]);
    await db.query("select public.falhar_apoio_sync('erro de consulta antiga',$1::timestamptz)", [oldToken]);
    assert.equal((await db.query('select erro from public.apoio_sync')).rows[0].erro, null, 'falha antiga não sobrescreve sincronização nova');
    await db.query("insert into public.apoio_ordens (chave,os,frota,ativo,primeira_vista,ultima_vista) select 'fixture-'||i::text,i::text,'999',false,now(),now() from generate_series(1,1050) i");
    await db.exec('set role anon;');
    assert.equal((await db.query('select count(*)::int as total from public.apoio_ordens')).rows[0].total, 1052);
    const full = (await db.query('select public.carregar_apoio_controle() as data')).rows[0].data;
    assert.equal(full.orders.length, 1052, 'fotografia completa não é truncada em 1.000 registros');
    assert.equal(full.fleets.length, 1);
    await assert.rejects(db.query('select public.iniciar_apoio_sync()'), /permission denied/i);
    await db.exec('reset role;');
    console.log('OK: SQL executado em PostgreSQL isolado; cadastro público, proteção de ordens, snapshots, histórico, reativação, falhas e limite por minuto verificados.');
  } finally { await db.close(); }
})();

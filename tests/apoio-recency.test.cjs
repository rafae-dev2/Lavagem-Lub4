const assert=require('node:assert/strict');
const {buildSync}=require('esbuild');
const Module=require('node:module');
const output=buildSync({entryPoints:['src/lib/apoioRecency.ts'],bundle:true,platform:'node',format:'cjs',write:false}).outputFiles[0].text;
const mod=new Module('recency-test');mod._compile(output,'recency-test.cjs');
const {DEFAULT_APOIO_RECENCY:defaults,selectApoioRecency:select,apoioRecencyTimestamp:stamp,apoioRecencyBounds:bounds}=mod.exports;
const now=new Date('2026-11-06T23:00:00Z');
const row=(id,entrada,status='Programada',first=entrada)=>({chave:id,os:id,frota:id,entrada,primeira_vista:first,ultima_vista:now.toISOString(),status,apoio:id,equipamento:'Teste'});
const rows=[row('20','2026-11-06T18:00:00-03:00','Programada','2026-11-06T22:50:00Z'),row('10','2026-11-06T19:00:00-03:00','Andamento','2026-11-06T20:00:00Z'),row('30','2026-11-05T23:00:00Z','Aguardando Peça'),row('40','2026-11-05T22:59:59Z'),row('50',''),row('60','2026-11-07T05:00:00Z'),row('70','2026-02-30T12:00:00Z')];
const copy=JSON.stringify(rows);
const opts=values=>({...defaults,...values});
const ids=selected=>selected.map(r=>r.chave);
assert.deepEqual(ids(select(rows,defaults,now)),['20','10','30','40','50','60','70']);
assert.deepEqual(ids(select(rows,opts({sort:'newest'}),now)),['10','20','30','40','50','60','70']);
assert.deepEqual(ids(select(rows,opts({sort:'oldest'}),now)),['40','30','20','10','50','60','70']);
assert.deepEqual(ids(select(rows,opts({sort:'newest',scheduledAndRunning:true}),now)),['10','20','40','50','60','70']);
assert.deepEqual(ids(select(rows,opts({window:'24h',sort:'newest'}),now)),['10','20','30']);
assert.deepEqual(ids(select(rows,opts({window:'1h',sort:'newest'}),now)),['10']);
assert.deepEqual(ids(select(rows,opts({window:'1h',sort:'newest',basis:'primeira_vista'}),now)),['20']);
assert.deepEqual(ids(select(rows,opts({window:'today',sort:'newest'}),now)),['10','20']);
const midnightRows=[row('1','2026-11-06T02:59:59Z'),row('2','2026-11-06T03:00:00Z')];
assert.deepEqual(ids(select(midnightRows,opts({window:'today'}),now)),['2']);
assert.equal(bounds(opts({window:'custom',start:'2026-11-08',end:'2026-11-07'}),now).error.length>0,true);
assert.deepEqual(select(rows,opts({window:'custom',start:'2026-11-08',end:'2026-11-07'}),now),[]);
assert.equal(bounds(opts({window:'custom',start:'2026-02-30'}),now).error.length>0,true);
const customRows=[row('1','2026-11-06T02:59:59.999Z'),row('2','2026-11-06T03:00:00Z'),row('3','2026-11-07T02:59:59.999Z'),row('4','2026-11-07T03:00:00Z')];
assert.deepEqual(ids(select(customRows,opts({window:'custom',start:'2026-11-06',end:'2026-11-06'}),new Date('2026-11-07T15:00:00Z'))),['2','3']);
assert.equal(stamp('2026-11-06 19:00:00'),Date.parse('2026-11-06T22:00:00Z'));
assert.equal(stamp('2026-02-30T12:00:00Z'),null);
assert.equal(stamp('2026-11-06T25:00:00Z'),null);
assert.equal(stamp('invalid'),null);
assert.equal(JSON.stringify(rows),copy);
const ties=[row('2','2026-11-06T21:00Z'),row('1','2026-11-06T21:00Z')];
assert.deepEqual(ids(select(ties,opts({sort:'newest'}),now)),['1','2']);
console.log('OK: recência validou fuso Brasília, entrada/primeira detecção, períodos, limites exatos, status, ordenação global, datas inválidas/futuras, intervalo e imutabilidade.');

const dataOutput=buildSync({entryPoints:['src/lib/apoioReportData.ts'],bundle:true,platform:'node',format:'cjs',write:false}).outputFiles[0].text;
const dataMod=new Module('recency-report-test');dataMod._compile(dataOutput,'recency-report-test.cjs');
const mixed=[{...rows[0],apoio:'A',origem:'Campo'},{...rows[1],apoio:'B',origem:'Campo'},{...rows[2],apoio:'A',origem:'Campo'}];
assert.deepEqual(ids(dataMod.exports.reportGroups(mixed,true).flatMap(g=>g.rows)),['20','10','30']);
assert.deepEqual(ids(dataMod.exports.reportGroups(mixed).flatMap(g=>g.rows)),['20','30','10']);
console.log('OK: PDF/imagens preservam ordem global por blocos adjacentes, modo organizado mantém agrupamento anterior.');
